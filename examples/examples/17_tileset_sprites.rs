#[cfg(test)]
mod tests {
    use super::{Mode, SPRITE_BASE, SPRITE_COUNT, SpriteId, sprite_for, sprite_for_site};
    use tilekit::world::{Biome, Site};

    #[test]
    fn every_biome_maps_to_a_sprite_inside_the_sheet() {
        for biome in Biome::ALL {
            let index = sprite_for(biome) as u32;
            assert!(
                index < SPRITE_COUNT,
                "{biome:?} maps to sprite {index}, past the end of the sheet"
            );
        }
    }

    #[test]
    fn every_sprite_codepoint_is_in_the_private_use_area() {
        for index in 0..SPRITE_COUNT {
            let ch = char::from_u32(SPRITE_BASE + index).expect("valid codepoint");
            assert!(
                ('\u{E000}'..='\u{F8FF}').contains(&ch),
                "sprite {index} is outside the private use area"
            );
        }
        assert_eq!(SpriteId::Ocean.glyph(), '\u{E000}');
        assert_eq!(SpriteId::Keep.glyph(), '\u{E00B}');
    }

    #[test]
    fn settlement_sprites_only_cover_the_sites_with_art() {
        assert_eq!(sprite_for_site(Site::Capital), Some(SpriteId::Town));
        assert_eq!(sprite_for_site(Site::Fort), Some(SpriteId::Keep));
        // These deliberately have no sprite and fall back to their glyph.
        assert_eq!(sprite_for_site(Site::Ruin), None);
        assert_eq!(sprite_for_site(Site::Mine), None);
        assert_eq!(sprite_for_site(Site::Shrine), None);
    }

    #[test]
    fn water_biomes_get_water_sprites() {
        for biome in Biome::ALL.iter().filter(|b| b.is_water()) {
            let sprite = sprite_for(*biome);
            assert!(
                matches!(sprite, SpriteId::Ocean | SpriteId::Shallows),
                "{biome:?} got the non-water sprite {sprite:?}"
            );
        }
    }

    #[test]
    fn mode_toggles_and_returns() {
        assert_eq!(Mode::Sprites.toggled(), Mode::Ascii);
        assert_eq!(Mode::Ascii.toggled(), Mode::Sprites);
        assert_eq!(Mode::Sprites.toggled().toggled(), Mode::Sprites);
    }
}
